# Mirror to apply to black
def mirror_pst(table: list):
    mirrored = []
    for rank in range(7, -1, -1):
        mirrored.extend(table[rank*8 : rank*8+8])
    return mirrored

PST_BLACK = {piece: mirror_pst(table) for piece, table in PST.items()}

def evaluate(piece_pos: dict, wk_pos: int, bk_pos: int):
    Eval = 0
    for piece, pos_list in piece_pos.items():
        for pos in pos_list:
            color = piece[0]
            ptype = piece[1]
            val = PIECE_VALUES[ptype]
            if color == 'w':
                val += PST[ptype][pos]
                Eval += val
            else:
                val += PST_BLACK[ptype][pos]
                Eval -= val
    Eval += PST['K'][wk_pos]
    Eval -= PST_BLACK['K'][bk_pos] 
    return Eval
